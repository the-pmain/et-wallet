import type { ISecretBuffer } from '@/core/encryption'
import type { KeyringType } from '@/core/keyring'
import type { AccountId, Address, DerivationPath, KeyringId, Timestamp } from '@/core/types'

/**
 * Аккаунт кошелька — ПУБЛИЧНАЯ проекция ключа.
 *
 * В этой структуре нет и не может быть приватного ключа. Она попадает
 * в состояние UI, сериализуется и хранится. Секреты живут отдельно.
 *
 * Идентификатор отделён от адреса намеренно: один и тот же адрес может быть
 * добавлен повторно из другого источника (сначала как наблюдаемый, затем
 * через аппаратный кошелёк), и привязка сущности к адресу привела бы
 * к потере пользовательского имени и настроек при переимпорте.
 */
export interface IAccount {
  readonly id: AccountId

  /** Адрес в контрольной сумме EIP-55. */
  readonly address: Address

  /** Имя, заданное пользователем либо назначенное по умолчанию. */
  readonly name: string

  /** Тип источника ключа. Определяет, можно ли аккаунт удалить. */
  readonly source: KeyringType

  /** Набор ключей, которому принадлежит аккаунт. */
  readonly keyringId: KeyringId

  /**
   * Путь деривации. `null` для импортированных аккаунтов: они
   * не принадлежат никакому дереву.
   */
  readonly derivationPath: DerivationPath | null

  /**
   * Индекс адреса в HD-дереве. `null` для импортированных.
   *
   * Хранится отдельно от пути, потому что используется напрямую при
   * подписи: `HDWalletService` принимает индекс, а не путь.
   */
  readonly addressIndex: number | null

  /**
   * Порядковый номер в списке. Задаётся пользователем перетаскиванием.
   * Не связан с индексом деривации: порядок отображения и позиция
   * в HD-дереве — разные вещи.
   */
  readonly order: number

  /**
   * Скрыт ли аккаунт в интерфейсе.
   *
   * Для HD-аккаунтов скрытие — единственная альтернатива удалению:
   * выведенный из seed-фразы аккаунт появится снова при следующем
   * восстановлении кошелька. Флаг честно отражает это ограничение.
   */
  readonly hidden: boolean

  readonly createdAt: Timestamp
}

/** Параметры создания аккаунта из HD-дерева. */
export interface ICreateAccountParams {
  /** Имя. Если не задано, назначается по порядковому номеру. */
  readonly name?: string

  /**
   * Номер адреса в дереве BIP-44.
   *
   * ОБЫЧНО НЕ ЗАДАЁТСЯ: кошелёк берёт следующий свободный. Явный номер
   * нужен восстановлению — там аккаунты создаются по найденным адресам,
   * а между ними бывают пропуски. Создать их подряд значило бы получить
   * другие адреса и не найти на них средств.
   */
  readonly addressIndex?: number
}

/** Параметры импорта приватного ключа. */
export interface IImportPrivateKeyParams {
  /**
   * Приватный ключ, 32 байта.
   *
   * Владение НЕ передаётся: буфер остаётся за вызывающим, и затирать
   * его обязан он. Сервис создаёт собственную копию для шифрования.
   */
  readonly privateKey: ISecretBuffer

  readonly name?: string
}

/** События слоя аккаунтов. */
export interface AccountEventMap {
  /**
   * Состав аккаунтов изменён.
   *
   * Соответствует событию `accountsChanged` стандарта EIP-1193.
   * Преобразование во внешний формат выполняет слой подключения dApp:
   * ядро не обязано знать о существовании dApp.
   */
  'account:listChanged': { readonly accounts: readonly Address[] }

  /** Активный аккаунт изменён. */
  'account:activeChanged': { readonly address: Address }
}
