/**
 * Расписание опроса курсов.
 *
 * ЧТО ЗДЕСЬ РЕШАЕТСЯ И ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ. Опрос живёт в хуке,
 * то есть в коде, который без окружения браузера не выполняется.
 * Расчёт задержки от него отделён, чтобы правило «сколько ждать после
 * отказа» проверялось обычным тестом, а не через поддельные таймеры.
 */

/**
 * Промежуток между опросами курсов.
 *
 * МИНУТА — ГРАНИЦА, ЗА КОТОРОЙ БЕСПЛАТНЫЙ ДОСТУП КОНЧАЕТСЯ. Курс
 * запрашивается отдельно для нативной валюты и по одному запросу
 * на каждый токен: пакет больше единицы бесплатный доступ отвергает
 * отказом `10012` — измерено. Кошелёк с тремя токенами тратит четыре
 * обращения на опрос, то есть 240 в час открытого экрана. Месячный
 * предел демонстрационного ключа — 10 000, и минутный шаг оставляет
 * около сорока часов работы в месяц. Шаг в пятнадцать секунд сжёг бы
 * этот предел за десять часов.
 *
 * Настоящего «реального времени» здесь нет и быть не может: потока
 * котировок источник не отдаёт, и опрос — единственный доступный
 * способ. Поэтому рядом с оценкой показывается время котировки:
 * обещать секундную точность, имея минутную, значило бы лгать.
 */
export const PRICE_REFRESH_INTERVAL_MS = 60_000

/**
 * Предел отступления при отказах.
 *
 * Восемь минут. Дальше растягивать нет смысла: за таким промежутком
 * пользователь всё равно нажмёт обновление сам.
 */
export const MAX_PRICE_REFRESH_INTERVAL_MS = 8 * 60_000

/**
 * Сколько ждать до следующего опроса.
 *
 * ОТКАЗЫ РАЗВОДЯТ ОПРОСЫ, А НЕ ПРЕКРАЩАЮТ ИХ. Бесплатный доступ
 * отвечает «429», когда частота превышена, и продолжать долбить его
 * с прежним шагом — верный способ не получить курсов до конца сессии.
 * Удвоение после каждого отказа выводит кошелёк из-под ограничения
 * само; первый же успех возвращает обычный шаг.
 *
 * Прекращать опрос совсем нельзя: отказ бывает разовым, а замерший
 * навсегда курс выглядел бы как исправно работающий и устаревший.
 */
export function nextPriceRefreshDelay(consecutiveFailures: number): number {
  if (consecutiveFailures <= 0) {
    return PRICE_REFRESH_INTERVAL_MS
  }

  const delay = PRICE_REFRESH_INTERVAL_MS * 2 ** consecutiveFailures

  return Math.min(delay, MAX_PRICE_REFRESH_INTERVAL_MS)
}
