import { describe, expect, it } from 'vitest'

import { parseAmount } from './amount-input'

describe('parseAmount', () => {
  it('переводит целое значение в минимальные единицы', () => {
    expect(parseAmount('1', 18)).toBe(10n ** 18n)
  })

  it('не теряет точность на дробных суммах', () => {
    /* `Number('0.1') * 1e18` даёт 100000000000000001 — на единицу
       больше запрошенного. Пользователь подтвердил бы одну сумму,
       а подписал другую. */
    expect(parseAmount('0.1', 18)).toBe(100_000_000_000_000_000n)
  })

  it('учитывает число знаков токена', () => {
    expect(parseAmount('1.5', 6)).toBe(1_500_000n)
  })

  it('принимает запятую как разделитель', () => {
    expect(parseAmount('0,25', 18)).toBe(250_000_000_000_000_000n)
  })

  it('принимает запись без целой части', () => {
    expect(parseAmount('.5', 18)).toBe(500_000_000_000_000_000n)
  })

  it('отвергает лишние знаки после запятой', () => {
    /* Округление означало бы отправку суммы, отличной от введённой. */
    expect(() => parseAmount('1.1234567', 6)).toThrow(/знаков после запятой/)
  })

  it('отвергает ноль', () => {
    expect(() => parseAmount('0', 18)).toThrow(/больше нуля/)
    expect(() => parseAmount('0.0', 18)).toThrow(/больше нуля/)
  })

  it('отвергает пустую строку', () => {
    expect(() => parseAmount('   ', 18)).toThrow(/Введите сумму/)
  })

  it('отвергает текст и отрицательные значения', () => {
    expect(() => parseAmount('много', 18)).toThrow()
    expect(() => parseAmount('-1', 18)).toThrow()
    expect(() => parseAmount('1e18', 18)).toThrow()
  })

  it('работает с токеном без дробной части', () => {
    expect(parseAmount('42', 0)).toBe(42n)
    expect(() => parseAmount('42.5', 0)).toThrow()
  })

  it('не теряет разряды на очень больших суммах', () => {
    expect(parseAmount('123456789.123456789123456789', 18)).toBe(
      123_456_789_123_456_789_123_456_789n,
    )
  })
})
