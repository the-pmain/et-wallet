import { toWholeUnits, type IBalance, type IPortfolioSummary } from '@/core'

/**
 * Оценка ПОКАЗАННОЙ суммы нативной валюты в долларах.
 *
 * СЧИТАЕТСЯ ОТ ПОКАЗАННОГО БАЛАНСА, А НЕ БЕРЁТСЯ ГОТОВОЙ ИЗ ПОЗИЦИИ.
 * В сводке портфеля у нативной позиции уже лежит `value`, и взять его
 * было бы короче. Но баланс обновляется отдельной кнопкой, которая
 * портфель не пересчитывает: после такого обновления готовая оценка
 * описывала бы прежнюю сумму. Рядом с крупно набранным числом стояла
 * бы цена другого числа — и заметить это неоткуда.
 *
 * Поэтому из сводки берётся только курс, а умножается на него ровно
 * та величина, которая выведена на экран. Курс при этом может быть
 * слегка устаревшим — это свойство любых курсов и оговорено словом
 * «примерно»; несовпадение суммы с её ценой свойством не является.
 *
 * СЕТЬ СВЕРЯЕТСЯ. При переключении сети баланс и сводка обновляются
 * не одновременно, и есть промежуток, в котором сводка ещё от прежней
 * сети. Без сверки баланс в BNB оказался бы оценён по курсу эфира,
 * то есть завышен в сотни раз.
 *
 * `null` — оценки нет: неизвестен баланс, курс либо согласие на
 * обращение к источнику курсов не дано. Ноль сюда не подставляется
 * никогда: «стоимость неизвестна» и «стоит ноль» — разные утверждения.
 */
export function estimateNativeValue(
  balance: IBalance | null,
  portfolio: IPortfolioSummary | null,
): number | null {
  if (balance === null || portfolio === null) {
    return null
  }

  /* Нативная валюта — единственная позиция без адреса контракта:
     у неё его нет по устройству сети. */
  const native = portfolio.positions.find((position) => position.token.address === null)

  if (native === undefined || native.quote === null) {
    return null
  }

  if (native.token.chainId !== balance.chainId) {
    return null
  }

  return toWholeUnits(balance.raw, balance.decimals) * native.quote.price
}
