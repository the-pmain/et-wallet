import type { StorageKey, StorageNamespace } from '@/core/storage'

import type { EncryptionKey } from './EncryptionKey'
import type { IEncryptedPayload, IKdfParams, ISecretBuffer } from './types'

/**
 * Симметричное шифрование данных пользователя.
 *
 * Границы ответственности:
 * - сервис шифрует и расшифровывает произвольные байты;
 * - сервис НЕ знает, что именно он шифрует, и НЕ хранит результат.
 *
 * Такое разделение позволяет тестировать шифрование независимо от хранилища
 * и исключает ситуацию, в которой шифрование «само решает», что считать
 * секретом.
 *
 * ДВА РЕЖИМА РАБОТЫ, и различие между ними существенно.
 *
 * 1. **Парольный** (`encrypt` / `decrypt`). Контейнер самодостаточен:
 *    содержит соль и параметры KDF, расшифровывается одним паролем.
 *    Каждая операция стоит полного вывода ключа — сотни миллисекунд.
 *    Применяется к хранилищу ключей, которое читается раз за сессию.
 *
 * 2. **Сессионный** (`deriveKey` + `encryptWithKey` / `decryptWithKey`).
 *    Ключ выводится один раз при разблокировке и держится в памяти.
 *    Операция стоит одного вызова AES. Применяется к отдельным записям.
 *
 * Без второго режима каждое чтение записи стоило бы 600 000 итераций
 * PBKDF2, что сделало бы приложение неработоспособным.
 *
 * Требования к любой реализации:
 * - только Web Crypto (`crypto.subtle`); собственных примитивов быть не должно;
 * - источник случайности — только `crypto.getRandomValues`, без внедрения:
 *   подменяемый генератор означает предсказуемые ключи;
 * - выведенный ключ создаётся с `extractable: false`;
 * - сравнение тегов аутентификации выполняет Web Crypto — собственных
 *   сравнений байтов быть не должно из-за атак по времени.
 */
export interface IEncryptionService {
  /**
   * Шифрует данные ключом, выведенным из пароля.
   *
   * Соль и вектор инициализации генерируются внутри метода заново
   * для каждого вызова.
   */
  encrypt(plaintext: Uint8Array, password: string): Promise<IEncryptedPayload>

  /**
   * Расшифровывает контейнер.
   *
   * @returns Буфер, который вызывающий обязан затереть после использования.
   * @throws DecryptionFailedError при неверном пароле либо нарушении целостности.
   *         Причина не детализируется: AES-GCM не различает эти случаи,
   *         а домысливание дало бы подбирающему пароль лишний сигнал.
   * @throws UnsupportedVaultVersionError если версия формата новее поддерживаемой.
   */
  decrypt(payload: IEncryptedPayload, password: string): Promise<ISecretBuffer>

  /**
   * Проверяет пароль без выдачи расшифрованных данных.
   *
   * Нужен для подтверждения необратимых операций (экспорт ключа, смена
   * пароля, сброс кошелька), где расшифрованное содержимое не требуется.
   */
  verifyPassword(payload: IEncryptedPayload, password: string): Promise<boolean>

  /**
   * Выводит сессионный ключ из пароля.
   *
   * Дорогая операция: выполняется один раз при разблокировке.
   * Возвращённый ключ вызывающий обязан уничтожить при блокировке.
   */
  deriveKey(password: string, params: IKdfParams): Promise<EncryptionKey>

  /**
   * Шифрует данные готовым сессионным ключом.
   *
   * Вектор инициализации генерируется заново на каждый вызов.
   * Повторное использование пары «ключ + IV» в AES-GCM полностью разрушает
   * стойкость режима, поэтому передать IV извне нельзя даже намеренно.
   */
  encryptWithKey(
    plaintext: Uint8Array,
    key: EncryptionKey,
    params: IKdfParams,
  ): Promise<IEncryptedPayload>

  /** Расшифровывает контейнер готовым сессионным ключом. */
  decryptWithKey(payload: IEncryptedPayload, key: EncryptionKey): Promise<ISecretBuffer>

  /** Параметры KDF для новых контейнеров. Соль генерируется внутри. */
  createKdfParams(): IKdfParams

  /**
   * Требуется ли перешифровать контейнер под актуальные параметры.
   *
   * Число итераций возрастает со временем вслед за ростом вычислительных
   * мощностей. Хранилище, созданное годы назад, защищено слабее нового.
   * Метод обнаруживает это при разблокировке — единственный момент,
   * когда пароль доступен и перешифровка возможна.
   */
  needsUpgrade(payload: IEncryptedPayload): boolean
}

/**
 * Хранилище, шифрующее записи прозрачно для вызывающего.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОЙ. `IStorageService` сознательно не шифрует: иначе
 * он начал бы сам решать, что считать секретом, и граница ответственности
 * размылась бы. `ISecureStorage` — обёртка над ним, добавляющая шифрование
 * и состояние блокировки.
 *
 * УСТРОЙСТВО. При инициализации создаётся заголовок с солью и проверочным
 * блоком. Разблокировка выводит из пароля сессионный ключ, расшифровывает
 * проверочный блок и держит ключ в памяти. Каждая запись шифруется этим
 * ключом со свежим вектором инициализации.
 *
 * ГАРАНТИЯ. Значение, прошедшее через `set`, попадает в нижележащее
 * хранилище только в зашифрованном виде. Приватные ключи и seed-фраза
 * в открытом виде на диск не записываются никогда.
 *
 * ЧЕГО СЛОЙ НЕ СКРЫВАЕТ. Имена пространств и ключей остаются открытыми,
 * как и размер значения. Наблюдатель с доступом к хранилищу увидит,
 * сколько аккаунтов у пользователя и когда они добавлялись, но не увидит
 * ни адресов, ни ключей.
 */
export interface ISecureStorage {
  /** Снята ли блокировка и доступен ли сессионный ключ. */
  readonly isUnlocked: boolean

  /** Создан ли заголовок хранилища. */
  isInitialized(): Promise<boolean>

  /**
   * Создаёт заголовок: генерирует соль и проверочный блок.
   *
   * После вызова хранилище остаётся разблокированным.
   *
   * @throws WalletAlreadyInitializedError если заголовок уже существует.
   */
  initialize(password: string): Promise<void>

  /**
   * Снимает блокировку.
   *
   * @throws InvalidPasswordError, WalletNotInitializedError
   */
  unlock(password: string): Promise<void>

  /**
   * Проверяет пароль, не меняя состояния блокировки.
   *
   * Нужен для подтверждения необратимых операций — выгрузки приватного
   * ключа, удаления импортированного аккаунта, сброса кошелька.
   *
   * Отдельная проверка при уже снятой блокировке не избыточна: снятая
   * блокировка означает лишь, что пароль вводили когда-то, а не что
   * за устройством сейчас находится владелец.
   */
  verifyPassword(password: string): Promise<boolean>

  /**
   * Ставит блокировку и отпускает сессионный ключ.
   *
   * Синхронный метод намеренно: блокировка обязана завершиться до возврата
   * управления в цикл событий, иначе остаётся промежуток, когда ключ ещё
   * доступен, а приложение считает себя заблокированным.
   */
  lock(): void

  /**
   * Читает и расшифровывает значение.
   *
   * @throws WalletLockedError если хранилище заблокировано.
   * @throws DecryptionFailedError при нарушении целостности записи.
   */
  get<TValue>(namespace: StorageNamespace, key: StorageKey): Promise<TValue | null>

  /**
   * Шифрует и записывает значение.
   *
   * @throws WalletLockedError если хранилище заблокировано.
   */
  set<TValue>(namespace: StorageNamespace, key: StorageKey, value: TValue): Promise<void>

  remove(namespace: StorageNamespace, key: StorageKey): Promise<void>

  has(namespace: StorageNamespace, key: StorageKey): Promise<boolean>

  keys(namespace: StorageNamespace): Promise<readonly StorageKey[]>

  /**
   * Меняет пароль, перешифровывая все записи.
   *
   * Операция атомарна: сбой посреди перезаписи не должен оставить часть
   * записей под старым ключом, а часть под новым — такое хранилище
   * не открылось бы ни одним паролем.
   *
   * @throws InvalidPasswordError
   */
  changePassword(currentPassword: string, newPassword: string): Promise<void>

  /**
   * Удаляет заголовок и все зашифрованные записи.
   *
   * НЕОБРАТИМАЯ ОПЕРАЦИЯ. Без сохранённой seed-фразы средства теряются.
   */
  destroy(): Promise<void>
}
